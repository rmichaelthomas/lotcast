#!/usr/bin/env python3
"""Generates src/tsa_pins.gu (pinned issuer certificates) and fixtures/tsa/tokens.json from the
chains and tokens that fetch_tsa_fixtures.sh saved. Run from packages/lotcast-log."""
import json
import re

TSAS = [
    ("digicert", "timestamp.digicert.com", "http://timestamp.digicert.com"),
    ("sectigo", "timestamp.sectigo.com", "http://timestamp.sectigo.com"),
    ("freetsa", "freetsa.org", "https://freetsa.org/tsr"),
]


def pem_blocks(path):
    text = open(path).read()
    return [re.sub(r"\s+", "", b) for b in re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", text, re.S)]


lines = [
    "# Generated by scripts/gen_tsa_pins.py from fixtures/tsa. Do not edit by hand.",
    "# Each pin is the base64 DER of the certificate that issued the TSA's signing certificate. A token",
    "# carries its own signing certificate (they rotate yearly); it is accepted only when a pinned issuer",
    "# issued it.",
    "",
]
tokens = {}
digest = open("fixtures/tsa/digest.hex").read().strip()
for name, host, url in TSAS:
    blocks = pem_blocks("fixtures/tsa/%s.chain.pem" % name)
    issuer = blocks[1]
    lines.append("pub fn tsa_issuer_%s() -> Text:" % name)
    lines.append('    return "%s"' % issuer)
    lines.append("")
    lines.append("pub fn tsa_host_%s() -> Text:" % name)
    lines.append('    return "%s"' % host)
    lines.append("")
    lines.append("pub fn tsa_url_%s() -> Text:" % name)
    lines.append('    return "%s"' % url)
    lines.append("")
    tokens[name] = open("fixtures/tsa/%s.token.b64" % name).read().strip()
open("src/tsa_pins.gu", "w").write("\n".join(lines))
json.dump({"digest": digest, "tokens": tokens}, open("fixtures/tsa/tokens.json", "w"))
print("wrote src/tsa_pins.gu and fixtures/tsa/tokens.json")
