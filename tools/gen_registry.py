#!/usr/bin/env python3
"""Generates the positions registry from one source of truth.

Writes registry/lotcast-registry-v1.json (CC0) and packages/lotcast-core/src/registry_data.gu.
Names are identifiers only (pinyin), never meanings. They are from memory until each tradition's
audit (spec §6) confirms them.

Run: python3 tools/gen_registry.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Trigram order for the King Wen lookup: Qian Zhen Kan Gen Kun Xun Li Dui. Bits are bottom to top.
TRIGRAMS = [("Qian", (1, 1, 1)), ("Zhen", (1, 0, 0)), ("Kan", (0, 1, 0)), ("Gen", (0, 0, 1)),
            ("Kun", (0, 0, 0)), ("Xun", (0, 1, 1)), ("Li", (1, 0, 1)), ("Dui", (1, 1, 0))]

# KING_WEN[lower][upper], both indexed in TRIGRAMS order.
KING_WEN = [
    [1, 34, 5, 26, 11, 9, 14, 43],
    [25, 51, 3, 27, 24, 42, 21, 17],
    [6, 40, 29, 4, 7, 59, 64, 47],
    [33, 62, 39, 52, 15, 53, 56, 31],
    [12, 16, 8, 23, 2, 20, 35, 45],
    [44, 32, 48, 18, 46, 57, 50, 28],
    [13, 55, 63, 22, 36, 37, 30, 49],
    [10, 54, 60, 41, 19, 61, 38, 58],
]

NAMES = ["Qian", "Kun", "Zhun", "Meng", "Xu", "Song", "Shi", "Bi", "Xiao Chu", "Lu", "Tai", "Pi",
         "Tong Ren", "Da You", "Qian", "Yu", "Sui", "Gu", "Lin", "Guan", "Shi He", "Bi", "Bo", "Fu",
         "Wu Wang", "Da Chu", "Yi", "Da Guo", "Kan", "Li", "Xian", "Heng", "Dun", "Da Zhuang", "Jin",
         "Ming Yi", "Jia Ren", "Kui", "Jian", "Xie", "Sun", "Yi", "Guai", "Gou", "Cui", "Sheng", "Kun",
         "Jing", "Ge", "Ding", "Zhen", "Gen", "Jian", "Gui Mei", "Feng", "Lu", "Xun", "Dui", "Huan",
         "Jie", "Zhong Fu", "Xiao Guo", "Ji Ji", "Wei Ji"]
assert len(NAMES) == 64

def hexagrams():
    out = {}
    for lower, row in enumerate(KING_WEN):
        for upper, number in enumerate(row):
            out[number] = list(TRIGRAMS[lower][1]) + list(TRIGRAMS[upper][1])
    assert sorted(out) == list(range(1, 65))
    return out

def registry_json():
    hx = hexagrams()
    return {
        "registry": "lotcast/registry/v1",
        "license": "CC0-1.0",
        "note": "Identifiers only: no meanings, keywords or texts. Names are from memory until the tradition's audit confirms them.",
        "iching": {"hexagrams": [
            {"id": f"iching:hexagram:{n}", "number": n, "lines": hx[n], "name": NAMES[n - 1]} for n in range(1, 65)]},
    }

def guion_data():
    rows = ", ".join("[" + ", ".join(str(n) for n in row) + "]" for row in KING_WEN)
    names = ", ".join(f'"{n}"' for n in NAMES)
    return f'''# Generated by tools/gen_registry.py from one source of truth. Do not edit by hand.
# The positions registry data (CC0): King Wen numbers by trigram, and hexagram names as identifiers.

# KING_WEN[lower][upper], both indexed Qian, Zhen, Kan, Gen, Kun, Xun, Li, Dui.
pub fn king_wen_table() -> List[List[Int]]:
    return [{rows}]

pub fn hexagram_names() -> List[Text]:
    return [{names}]
'''

if __name__ == "__main__":
    (ROOT / "registry" / "lotcast-registry-v1.json").write_text(json.dumps(registry_json(), indent=2) + "\n")
    (ROOT / "packages" / "lotcast-core" / "src" / "registry_data.gu").write_text("import \"std:types\"\n\n" + guion_data())
    print("registry written")
